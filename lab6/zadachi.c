//31. Характеристикой строки целочисленной матрицы назовем сумму ее отрицательных
// четных элементов. Переставляя строки заданной матрицы, расположить их
// в соответствии с убыванием характеристик.
//Тест (3x4) - ввести:
// 3 4
//  1  -2   3  -4     характеристика = -2 + -4 = -6
//  5   6  -7   8     характеристика =  0 (нет отрицательных четных)
// -2   1   1   1     характеристика = -2

#include <stdio.h>
#include <stdlib.h>

int main() {
    int **a;           // указатель на массив указателей (на строки)
    int *ch;           // динамический массив характеристик строк
    int n, m, i, j;
    int *tmpRow;       // для обмена строк
    int tmp;           // для обмена характеристик

    printf("Введите количество строк и столбцов:\n");
    scanf("%d %d", &n, &m);

    // выделяем память: сначала массив из n указателей на строки
    a = (int **)malloc(n * sizeof(int *));
    if (a == NULL) {
        printf("Не хватает памяти\n");
        return 1;
    }
    // потом каждую строку из m чисел
    for (i = 0; i < n; i++) {
        *(a + i) = (int *)malloc(m * sizeof(int));
        if (*(a + i) == NULL) {
            printf("Не хватает памяти\n");
            return 1;
        }
    }
    ch = (int *)malloc(n * sizeof(int));
    if (ch == NULL) {
        printf("Не хватает памяти\n");
        return 1;
    }

    printf("Введите элементы матрицы %dx%d:\n", n, m);
    for (i = 0; i < n; i++)
        for (j = 0; j < m; j++)
            scanf("%d", *(a + i) + j);           // адрес элемента a[i][j]

    printf("\nИсходная матрица:\n");
    for (i = 0; i < n; i++) {
        for (j = 0; j < m; j++)
            printf("%5d", *(*(a + i) + j));      // значение a[i][j]
        printf("\n");
    }

    // считаем характеристику каждой строки
    for (i = 0; i < n; i++) {
        *(ch + i) = 0;
        for (j = 0; j < m; j++) {
            int x = *(*(a + i) + j);
            if (x < 0 && x % 2 == 0)             // отрицательный И четный
                *(ch + i) += x;
        }
    }

    printf("\nХарактеристики строк:\n");
    for (i = 0; i < n; i++)
        printf("Строка %d: %d\n", i + 1, *(ch + i));

    // сортировка пузырьком по УБЫВАНИЮ характеристик
    for (i = 0; i < n - 1; i++)
        for (j = 0; j < n - 1 - i; j++)
            if (*(ch + j) < *(ch + j + 1)) {     // меньшая стоит выше - меняем
                // меняем местами характеристики
                tmp = *(ch + j);
                *(ch + j) = *(ch + j + 1);
                *(ch + j + 1) = tmp;
                // меняем местами строки (просто меняем указатели на них)
                tmpRow = *(a + j);
                *(a + j) = *(a + j + 1);
                *(a + j + 1) = tmpRow;
            }

    printf("\nМатрица после сортировки строк:\n");
    for (i = 0; i < n; i++) {
        for (j = 0; j < m; j++)
            printf("%5d", *(*(a + i) + j));
        printf("   | характеристика = %d\n", *(ch + i));
    }

    // освобождаем память: сначала строки, потом массив указателей
    for (i = 0; i < n; i++)
        free(*(a + i));
    free(a);
    free(ch);

    return 0;
}